def run(cmd: str, timeout: int = 30) -> "subprocess.CompletedProcess":
    """Run *cmd* in a shell, capturing output. Never raises."""
    try:
        return subprocess.run(cmd, shell=True, capture_output=True,
                              text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return subprocess.CompletedProcess(cmd, 124, "", f"timeout after {timeout}s")


def _write_atomic(path: Path, text: str, mode: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    tmp.chmod(mode)
    os.replace(tmp, path)


def backup(path: Path) -> str:
    """Copy *path* to <path>.bak-<UTC timestamp>. '' if source missing."""
    if not path.is_file():
        return ""
    ts = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    bak = path.with_name(path.name + f".bak-{ts}")
    bak.write_bytes(path.read_bytes())
    try:
        bak.chmod(path.stat().st_mode & 0o777)
    except OSError:
        pass
    return str(bak)


