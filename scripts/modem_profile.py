def cmd_status(_args) -> int:
    ps = paths()
    active = read_active()
    prof = None
    print(f"Active profile : {active or '<none>'}")
    if active:
        path = profile_path(active)
        if path.is_file():
            prof = load_profile(path)
            print(f"  modem        : {prof['modem_model']}")
            print(f"  vid:pid      : {prof.get('vid_pid') or '-'}")
            print(f"  channel      : {prof['dongle_name']}  "
                  f"(audio={prof['audio_device'] or '-'} "
                  f"data={prof['data_device']})")
            if prof.get("alsadev"):
                print(f"  UAC voice    : alsadev={prof['alsadev']}")
            print(f"  verified     : {prof['verified']}")

    r = run("lsusb 2>/dev/null")
    kw = re.compile(r"huawei|quectel|dacom|simcom|telit|wavecom|gsm|modem", re.I)
    print("Plugged in USB :")
    found = False
    for line in r.stdout.splitlines():
        if not kw.search(line):
            continue
        found = True
        m = re.search(r"\b([0-9a-fA-F]{4}):([0-9a-fA-F]{4})\b", line)
        vidpid = f"{m.group(1).lower()}:{m.group(2).lower()}" if m else "?"
        mark = ""
        if prof and prof.get("vid_pid"):
            mark = "  MATCH" if vidpid == prof["vid_pid"].lower() else \
                "  MISMATCH (profile says " + prof["vid_pid"] + ")"
        print(f"  {vidpid}  {mark}  {line.strip()}")
    if not found:
        print("  (no modem keyword match in lsusb — is the modem plugged in?)")

    r = run("asterisk -rx 'dongle show devices' 2>&1", timeout=15)
    print("dongle devices :")
    for line in (r.stdout or r.stderr).splitlines():
        print(f"  {line}")
    r = run("systemctl is-active simbridge-agent 2>&1")
    print(f"simbridge-agent: {r.stdout.strip()}")

    # ModemManager must not manage the dongle (chan_dongle owns the
    # ports). The rendered ID_MM_DEVICE_IGNORE tags block FRESH
    # enumeration; if MM adopted the dongle before the rule existed
    # (e.g. it was plugged in earlier), a udev change event will NOT
    # make it drop the device — a one-time service restart will.
    mm = run("systemctl is-active ModemManager 2>&1")
    if mm.stdout.strip() == "active":
        r = run("mmcli -L 2>/dev/null")
        modems = [l for l in r.stdout.splitlines() if l.startswith("/")]
        if modems:
            print("ModemManager   : ACTIVE — managing modems:")
            for l in modems:
                print(f"  {l}")
            print("  (the dongle must not be among them; if the channel "
                  "is stuck 'Not connec' with EBUSY in the Asterisk "
                  "log, run: systemctl restart ModemManager)")
        else:
            print("ModemManager   : active, no managed modems")
    return 0


