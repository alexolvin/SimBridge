def validate_profile(p: dict) -> list:
    """Return a list of error strings (empty = valid)."""
    errors = []
    for k in ("name", "modem_model", "dongle_name", "data_device"):
        if not isinstance(p.get(k), str) or not p.get(k).strip():
            errors.append(f"{k}: required non-empty string")
    # Voice path: exactly one of audio_device (serial PCM tty) or alsadev
    # (UAC ALSA card, chan_dongle patch 0003) — never both, never neither.
    audio = p.get("audio_device")
    alsadev = p.get("alsadev")
    if not isinstance(audio, str):
        audio = ""
    if alsadev is not None and not isinstance(alsadev, str):
        errors.append("alsadev: must be a string (empty = serial audio tty)")
        alsadev = ""
    alsadev = alsadev or ""
    if not audio.strip():
        if not alsadev:
            errors.append("audio_device: required non-empty string "
                          "(or set alsadev for UAC voice)")
    elif alsadev:
        errors.append("audio_device and alsadev are mutually exclusive "
                      "(UAC voice uses the ALSA card, not a serial tty)")
    if alsadev and re.search(r"\s", alsadev):
        errors.append("alsadev: must not contain whitespace "
                      "(e.g. hw:CARD=EC25EUX,DEV=0)")
    name = p.get("name") or ""
    if isinstance(name, str) and name and \
            not re.fullmatch(r"[a-z0-9][a-z0-9-]*", name):
        errors.append("name: must match [a-z0-9][a-z0-9-]* (lowercase, dashes)")
    vid = p.get("vid_pid", "")
    if vid is None:
        vid = ""
    if vid and not re.fullmatch(r"[0-9a-fA-F]{4}:[0-9a-fA-F]{4}", str(vid)):
        errors.append(f"vid_pid: {vid!r} — must be 'vvvv:pppp' or empty")
    if not isinstance(p.get("verified"), bool):
        errors.append("verified: required boolean (true only after live E2E)")
    udev = p.get("udev", [])
    if not isinstance(udev, list):
        errors.append("udev: required list of {iface, symlink} (may be empty)")
    else:
        for i, e in enumerate(udev):
            if not isinstance(e, dict):
                errors.append(f"udev[{i}]: must be a mapping")
                continue
            if not re.fullmatch(r"\d{2}", str(e.get("iface", ""))):
                errors.append(
                    f"udev[{i}].iface: required 2-digit USB interface number")
            if not isinstance(e.get("symlink"), str) or not e.get("symlink"):
                errors.append(f"udev[{i}].symlink: required non-empty string")
    return errors


def _ys(v) -> str:
    """Double-quoted single-line YAML scalar (safe for colons/spaces)."""
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_profile(p: dict) -> str:
    """Serialize a profile dict to its on-disk YAML (fixed key order)."""
    lines = [
        f"# SimBridge modem profile — {p['name']}",
        "# Written by scripts/modem_profile.py (new/capture/probe/init).",
        "# 'verified' means a live end-to-end test on this modem passed.",
        "name: " + _ys(p["name"]),
        "modem_model: " + _ys(p.get("modem_model", "")),
        "vid_pid: " + _ys(p.get("vid_pid", "")),
        f"dongle_name: {p['dongle_name']}",
        f"audio_device: {p['audio_device']}",
        f"data_device: {p['data_device']}",
    ]
    # alsadev only for UAC profiles — an empty line would break the
    # render/load roundtrip on serial profiles
    if p.get("alsadev"):
        lines.append("alsadev: " + _ys(p["alsadev"]))
    lines += [
        "sim_phone: " + _ys(p.get("sim_phone", "")),
        "udev:",
    ]
    for e in p.get("udev", []):
        lines.append(f'  - {{iface: "{e["iface"]}", symlink: {e["symlink"]}}}')
    if not p.get("udev"):
        lines[-1] = "udev: []"
    lines.append(f"verified: {str(p['verified']).lower()}")
    lines.append("notes: " + _ys(p.get("notes", "")))
    return "\n".join(lines) + "\n"


def load_profile(path: Path) -> dict:
    with open(path) as fh:
        p = yaml.safe_load(fh)
    if not isinstance(p, dict):
        raise ProfileError(f"invalid profile (not a mapping): {path}")
    errs = validate_profile(p)
    if errs:
        raise ProfileError(f"invalid profile {path}:\n  - " + "\n  - ".join(errs))
    # 'audio_device: ' (UAC profiles) parses to None — normalize to ""
    p["audio_device"] = p.get("audio_device") or ""
    p.setdefault("vid_pid", "")
    p.setdefault("sim_phone", "")
    p.setdefault("udev", [])
    p.setdefault("notes", "")
    return p


def profile_path(name: str) -> Path:
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", name or ""):
        raise ProfileError(f"invalid profile name: {name!r}")
    return paths()["profiles_dir"] / f"{name}.yaml"


def write_profile(p: dict) -> Path:
    errs = validate_profile(p)
    if errs:
        raise ProfileError("invalid profile:\n  - " + "\n  - ".join(errs))
    path = profile_path(p["name"])
    _write_atomic(path, render_profile(p), 0o644)
    return path


def read_active() -> str:
    p = paths()["active"]
    if p.is_file():
        name = p.read_text().strip()
        if name:
            return name
    return ""


def write_active(name: str) -> None:
    p = paths()["active"]
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(name + "\n")
    p.chmod(0o644)


