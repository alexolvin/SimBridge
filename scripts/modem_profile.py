# Canonical EC2x (0x2C7C) USB interface numbering, per the Quectel
# "USB Interface Descriptor" doc (Table 2). cmd_probe trusts this map only
# when the empirical AT port (AT+CGMM) sits at its canonical slot.
_EC2X_IFACE_ROLES = {"00": "dm", "01": "nmea", "02": "at", "03": "modem"}


def interpret_usbcfg(usbcfg: str) -> str:
    """Decode an AT+QCFG="USBCFG" answer and state the voice path.

    EC2x numeric format (Quectel QCFG manual 9.2, 0x2C7C PIDs):
      +QCFG: "usbcfg",<vid>,<pid>,<diag>,<nmea>,<at_port>,<modem>,
             <rmnet>,<adb>,<uac>
    — seven 0/1 port flags after vid/pid. Older firmwares answer a named
    mode string instead (EC20-style "QMI,ECM,...,AUD,...,UAC=0"); a
    keyword fallback covers that.

    Voice options per the Quectel EC2x "Voice Over USB and UAC" app note:
      - serial PCM via the NMEA port (AT+QPCMV option 0) — usable via the
        serial audio tty; needs nmea=1 and the NMEA port free of GNSS
        output;
      - UAC USB sound card (uac=1) — usable via the alsadev setting
        (chan_dongle patch 0003): voice rides a virtual USB sound card,
        located at probe time from /proc/asound/cards.
    Returns 'uac', 'serial', or 'none' (the usable voice path).
    """
    parts = [f.strip() for f in
             usbcfg.split('"')[-1].strip().strip(',').split(',')]
    if (len(parts) == 9
            and all(re.fullmatch(r"0x[0-9A-Fa-f]+", f) for f in parts[:2])
            and all(re.fullmatch(r"[01]", f) for f in parts[2:])):
        diag, nmea, at_p, modem, net, adb, uac = (int(f) for f in parts[2:])
        print(f"  ports          : diag={diag} nmea={nmea} at={at_p} "
              f"modem={modem} net={net} adb={adb} uac={uac}")
        if uac:
            print("  voice          : UAC (USB sound card) — supported by "
                  "this chan_dongle build (patch 0003); probe locates the "
                  "card, record it in the profile alsadev")
            return "uac"
        elif nmea:
            print("  voice          : SERIAL PCM via the NMEA port "
                  "(AT+QPCMV option 0) — usable by this chan_dongle "
                  "build; the NMEA port must be free of GNSS output")
            return "serial"
        else:
            print("  voice          : NO voice port exposed (nmea=0, uac=0) "
                  '— change the mode (AT+QCFG="USBCFG",...) and re-probe')
            return "none"
    # legacy named mode string (EC20-style)
    serial_audio = "Audio" in usbcfg or "AUD" in usbcfg
    uac = "UAC=1" in usbcfg or (
        re.findall(r'"([^"]*)"', usbcfg)
        and "UAC" in re.findall(r'"([^"]*)"', usbcfg)[-1])
    if serial_audio:
        print("  voice          : SERIAL audio port present — "
              "chan_dongle can use it")
        return "serial"
    elif uac:
        print("  voice          : UAC (USB sound card) only — supported "
              "by this chan_dongle build (patch 0003); record the card "
              "in the profile alsadev")
        return "uac"
    else:
        print("  voice          : no voice port in this USBCFG mode — "
              "change mode and re-probe")
        return "none"


def _find_uac_card(hint: str = "") -> str:
    """Locate the modem's UAC sound card among the ALSA cards.

    /proc/asound/cards lists 'N [SHORT]: Bus - long name' (the long
    name may continue on the next indented line). The first USB-Audio
    card whose name matches *hint* (case-insensitive substring; empty
    hint = any USB-Audio card) that has BOTH a capture and a playback
    PCM0 wins. The card name changes across USB re-enumerations, so it
    is always read from the live state, never hardcoded.
    Returns 'hw:CARD=<short>,DEV=0' or ''.
    """
    r = run("cat /proc/asound/cards 2>/dev/null")
    cards = []
    lines = (r.stdout or "").splitlines()
    i = 0
    while i < len(lines):
        # the short name is whitespace-padded inside the brackets:
        # ' 3 [EC25EUX        ]: USB-Audio - EC25-EUX'
        m = re.match(r"^\s*(\d+)\s+\[([^\]]+)\]\s*:\s*(\S+)\s*-\s*(.*)$",
                     lines[i])
        if m:
            desc = m.group(4)
            if i + 1 < len(lines) and lines[i + 1][:1] == " ":
                desc += " " + lines[i + 1].strip()
                i += 1
            cards.append((m.group(1), m.group(2).strip(),
                          m.group(3), desc))
        i += 1
    for idx, short, bus, desc in cards:
        if bus != "USB-Audio":
            continue
        if hint and hint.lower() not in f"{short} {desc}".lower():
            continue
        card = f"/proc/asound/card{idx}"
        if run(f"test -e {card}/pcm0c -a -e {card}/pcm0p").returncode == 0:
            return f"hw:CARD={short},DEV=0"
    return ""


def cmd_probe(args) -> int:
    devs = _probe_devices()
    if not devs:
        raise ProfileError("no ttyUSB/ttyACM devices found — "
                           "is the modem plugged in?")
    # Warn if Asterisk is actually CONNECTED to a dongle (State Free/Busy) —
    # then probe would interleave with chan_dongle's own AT traffic. A
    # channel that is "Not connec"/"OFFLINE" holds no port.
    r = run("asterisk -rx 'dongle show devices' 2>&1", timeout=15)
    if r.returncode == 0 and re.search(r"\b(Free|Busy)\b", r.stdout or ""):
        print("[warn] a dongle is CONNECTED in Asterisk — for a clean "
              "probe stop it first: systemctl stop asterisk")

    print("Discovered ports:")
    for d in devs:
        print(f"  {d['dev']:16s} vid:pid={d['vid']}:{d['pid']} "
              f"iface={d['iface'] or '-'}  {d['model'][:50]}")

    # AT+CGMM is the decisive probe: only the module's AT port answers it
    # (audio/data TTYs have no modem controller behind them).
    at_dev, cgmm = None, ""
    for d in devs:
        cgmm_try = at_query(d["dev"], "AT+CGMM")
        if cgmm_try:
            at_dev, cgmm = d["dev"], cgmm_try
            break
    print(f"AT port        : {at_dev or 'NOT FOUND'}"
          + (f"  (AT+CGMM -> {cgmm})" if cgmm else ""))

    voice_mode = ""
    alsadev_guess = ""
    if at_dev:
        usbcfg = at_query(at_dev, 'AT+QCFG="USBCFG"')
        if usbcfg:
            print(f"USBCFG         : {usbcfg}")
            voice_mode = interpret_usbcfg(usbcfg)
        else:
            print("USBCFG         : no answer (not a Quectel module or "
                  "unsupported)")

        # Serial voice (Voice over USB): per the Quectel EC2x app note the
        # PCM stream rides the NMEA port (AT+QPCMV option 0), so QPCMV must
        # be supported and the NMEA port must be free of GNSS output.
        qpcmv = at_query(at_dev, "AT+QPCMV?")
        if qpcmv:
            if voice_mode == "uac":
                print(f"QPCMV          : {qpcmv}  — the driver arms "
                      "AT+QPCMV=1,2 per call (UAC transport)")
            else:
                print(f"QPCMV          : {qpcmv}  — serial voice supported "
                      "(chan_dongle arms it per call)")
        else:
            print("QPCMV          : no answer — serial voice NOT available "
                  "on this firmware")
        gps_out = at_query(at_dev, 'AT+QGPSCFG="outport"')
        if gps_out:
            print(f"GPS outport    : {gps_out}")
            # Firmware answers the value with or without quotes
            # (live EC25: '+QGPSCFG: "outport",usbnmea') — match both.
            if re.search(r"\busbnmea\b", gps_out):
                print("  [warn] GNSS output is ON the USB NMEA port — before "
                      "serial voice set AT+QGPSCFG=\"outport\",\"none\"")

        # UAC voice: the audio path is a virtual USB sound card, not a tty.
        # The card is only guaranteed to exist after a USB re-enumeration
        # with USBCFG uac=1, so it is located live, never hardcoded.
        if voice_mode == "uac":
            alsadev_guess = _find_uac_card(cgmm)
            if alsadev_guess:
                print(f"UAC card       : {alsadev_guess}  (record it as "
                      "alsadev in the profile)")
            else:
                print("UAC card       : NOT FOUND among the ALSA cards — "
                      "check /proc/asound/cards (the card appears only "
                      "after a USB re-enumeration with USBCFG uac=1)")

    # Guess: data = AT port (empirical, via AT+CGMM). Audio = the voice
    # port: for EC2x (0x2C7C) the Quectel USB interface descriptor doc
    # fixes the numbering (0=DM, 1=NMEA, 2=AT, 3=Modem) and serial voice
    # PCM rides the NMEA port — when the empirical AT port sits at its
    # canonical slot the map is trusted and audio = the NMEA port.
    # Everything else falls back to the first non-AT port that is not the
    # EC2x DM/diag slot (still UNVERIFIED — confirm before use).
    data_guess = at_dev or ""
    audio_guess = ""
    at_entry = next((d for d in devs if d["dev"] == at_dev), None)
    if (at_entry is not None and at_entry["vid"].lower() == "2c7c"
            and _EC2X_IFACE_ROLES.get(at_entry["iface"]) == "at"):
        audio_guess = next((d["dev"] for d in devs
                            if _EC2X_IFACE_ROLES.get(d["iface"]) == "nmea"),
                           "")
    if not audio_guess:
        for d in devs:
            if (d["dev"] != at_dev and re.fullmatch(r"\d{2}", d["iface"])
                    and not (d["vid"].lower() == "2c7c"
                             and _EC2X_IFACE_ROLES.get(d["iface"]) == "dm")):
                audio_guess = d["dev"]
                break
    if alsadev_guess:
        print(f"Guess          : data={data_guess or '?'}  "
              f"alsadev={alsadev_guess}   (UAC voice — UNVERIFIED, "
              "confirm before use)")
    else:
        print(f"Guess          : data={data_guess or '?'}  "
              f"audio={audio_guess or '?'}   (UNVERIFIED — confirm before use)")

    if not args.commit:
        print("\nReview the mapping, then:")
        voice = (f" --alsadev {shlex.quote(alsadev_guess)}"
                 if alsadev_guess
                 else f" --audio {shlex.quote(audio_guess)}")
        print(f"  modem_profile.py probe --commit <name> "
              f"--data {shlex.quote(data_guess)}{voice}")
        return 0

    # --commit: write/extend the profile from the findings.
    vid = pid = ""
    for d in devs:
        if d["vid"] and d["pid"]:
            vid, pid = d["vid"], d["pid"]
            break
    data_dev = args.data or data_guess
    audio_dev = args.audio or audio_guess
    # UAC voice: an explicit --alsadev wins over the live card detection.
    # In UAC mode there is no PCM on the serial ports — the serial audio
    # guess is not a voice path, alsadev is the only one.
    alsadev = getattr(args, "alsadev", "") or \
        (alsadev_guess if voice_mode == "uac" else "")
    if voice_mode == "uac":
        audio_dev = ""
    if not data_dev:
        raise ProfileError("probe --commit: could not determine the data "
                           "port — pass --data explicitly")
    if not alsadev and not audio_dev:
        raise ProfileError("probe --commit: could not determine the voice "
                           "path — pass --audio (serial PCM port) or "
                           "--alsadev (UAC card) explicitly")
    # Audio via the stable udev symlink (dongle_if<iface>), data via symlink too.
    iface_of = {d["dev"]: d["iface"] for d in devs}
    udev_map = []
    for d in sorted(devs, key=lambda x: (x["iface"] or "99")):
        if re.fullmatch(r"\d{2}", d["iface"]):
            udev_map.append({"iface": d["iface"],
                             "symlink": f"dongle_if{int(d['iface'])}"})
    def _as_symlink(dev):
        iface = iface_of.get(dev, "")
        # dongle_if<iface-as-integer> — the live convention (iface "01"
        # is dongle_if1, not dongle_if01)
        return f"/dev/dongle_if{int(iface)}" if iface else dev

    ps = paths()
    name = args.commit
    existing = profile_path(name)
    p = load_profile(existing) if existing.is_file() else {
        "name": name, "modem_model": "", "vid_pid": "", "dongle_name": "gsm",
        "audio_device": "", "data_device": "", "sim_phone": "",
        "udev": [], "verified": False, "notes": "",
    }
    p["modem_model"] = (next((d["model"] for d in devs if d["model"]), "")
                        or p["modem_model"])
    if vid and pid:
        p["vid_pid"] = f"{vid}:{pid}"
    if alsadev:
        p["audio_device"] = ""
        p["alsadev"] = alsadev
    else:
        p["audio_device"] = _as_symlink(audio_dev)
        p.pop("alsadev", None)
    p["data_device"] = _as_symlink(data_dev)
    if udev_map:
        p["udev"] = udev_map
    p["verified"] = False
    p["notes"] = ("probe: AT+CGMM answered on data port; port mapping is a "
                  "GUESS until a live E2E test passes — see "
                  "AT/USBCFG output in the session log")
    write_profile(p)
    print(f"\nProfile written: {profile_path(name)} (verified: false)")
    if alsadev:
        print(f"  UAC voice  : alsadev={alsadev} (audio= not used; the "
              "asterisk user must be in the 'audio' group)")
    print("Verify with a real SMS/call, then: "
          f"modem_profile.py use {name} --force")
    return 0


def cmd_init(args) -> int:
    """Fresh-install path (called by deploy/install.py): create the profile
    from installer answers and render the artifacts. No restarts — the
    installer starts services itself."""
    path = profile_path(args.name)
    if path.exists() and not args.force:
        raise ProfileError(f"profile already exists: {path} (use --force)")
    udev = []
    if args.vid_pid:
        for iface in (i.strip() for i in (args.interfaces or "00,01,02").split(",")):
            if re.fullmatch(r"\d{2}", iface):
                udev.append({"iface": iface, "symlink": f"dongle_if{int(iface)}"})
    p = {
        "name": args.name,
        "modem_model": args.modem_model or "",
        "vid_pid": args.vid_pid or "",
        "dongle_name": args.dongle_name or "gsm",
        "audio_device": args.audio or "/dev/dongle_if1",
        "data_device": args.data or "/dev/dongle_if2",
        "sim_phone": args.sim_phone or "",
        "udev": udev,
        "verified": False,
        "notes": "created by install.py (fresh install) — refine with "
                 "probe/capture after the first live test",
    }
    write_profile(p)
    write_active(args.name)
    apply_artifacts(p, backup_old=True)
    print(f"Profile {args.name} created and active; artifacts rendered.")
    return 0


def cmd_apply(args) -> int:
    path = profile_path(args.name)
    if not path.is_file():
        raise ProfileError(f"no such profile: {args.name}")
    p = load_profile(path)
    res = apply_artifacts(p, backup_old=True)
    print(f"Artifacts rendered for {args.name}:")
    print(f"  udev      : {res['udev'] or '(unchanged or not rendered)'}")
    print(f"  dongle    : {res['dongle_conf']}")
    for b in res["backups"]:
        print(f"  backup    : {b}")
    print("No services were restarted (use `use` for a full switch).")
    return 0


def _switch(name: str, force: bool) -> int:
    ps = paths()
    path = profile_path(name)
    if not path.is_file():
        raise ProfileError(f"no such profile: {name}")
    p = load_profile(path)
    if not p["verified"] and not force:
        raise ProfileError(
            f"profile {name} is NOT verified (verified: false).\n"
            f"  Run a live end-to-end check first (SMS/call) and set "
            f"verified: true — or re-run with --force to acknowledge the\n"
            f"  unverified state explicitly.")

    prev = read_active()
    udev_text = None
    if p.get("vid_pid") and p.get("udev"):
        udev_text = render_udev_rules(p)
    dtext = render_dongle_conf(p)

    yaml_text = ps["config_yaml"].read_text() if ps["config_yaml"].is_file() \
        else ""
    old_dongle = _yaml_field(yaml_text, "asterisk", "dongle") if yaml_text \
        else ""
    new_yaml = yaml_text
    if yaml_text:
        new_yaml = patch_yaml_field(yaml_text, "asterisk", "dongle",
                                    p["dongle_name"], quote=False)
        new_yaml = patch_yaml_field(new_yaml, "sim", "modem_model",
                                    p["modem_model"])

    in_sync = (
        prev == name
        and (udev_text is None
             or (ps["udev_rule"].is_file()
                 and ps["udev_rule"].read_text() == udev_text))
        and ps["dongle_conf"].is_file()
        and ps["dongle_conf"].read_text() == dtext
        and new_yaml == yaml_text
    )
    if in_sync:
        print(f"Profile {name} is already active and all artifacts are in "
              f"sync — nothing to do (no restarts).")
        return 0

    print(f"Switching modem profile: {prev or '<none>'} -> {name}")
    res = apply_artifacts(p, backup_old=True)
    if yaml_text:
        _write_atomic(ps["config_yaml"], new_yaml, 0o644)
        print(f"  Updated {ps['config_yaml']}: "
              f"asterisk.dongle={p['dongle_name']}, sim.modem_model")
    else:
        print(f"  [warn] {ps['config_yaml']} not found — skipped yaml update")
    write_active(name)
    print(f"  Active pointer: {ps['active']} -> {name}")

    gen = str(GENERATOR)
    r = run(f"{sys.executable} {shlex.quote(gen)} {shlex.quote(str(ps['config_yaml']))} "
            f"-o {shlex.quote(str(ps['globals']))}", timeout=60)
    if r.returncode == 0:
        print(f"  Regenerated {ps['globals']} (existing generator)")
    else:
        print(f"  [warn] globals regeneration failed: "
              f"{(r.stderr or r.stdout).strip()[:300]}")

    print("Restarting services...")
    run("systemctl restart asterisk")
    print("  asterisk restarted")
    if old_dongle and old_dongle != p["dongle_name"]:
        run("systemctl restart simbridge-agent")
        print(f"  simbridge-agent restarted (channel name "
              f"{old_dongle} -> {p['dongle_name']})")
    else:
        print("  simbridge-agent NOT restarted (channel name unchanged)")

    # Verify — retry a few times while Asterisk comes up.
    ok = False
    out = ""
    for _ in range(4):
        time.sleep(3)
        r = run("asterisk -rx 'dongle show devices' 2>&1", timeout=15)
        out = r.stdout
        ok = r.returncode == 0 and p["dongle_name"] in out
        if ok:
            break
    ra = run("systemctl is-active simbridge-agent 2>&1")
    agent_ok = ra.stdout.strip() == "active"

    print("\nVerification:")
    for line in (out or "").splitlines():
        print(f"  {line}")
    print(f"  simbridge-agent: {ra.stdout.strip()}")

    if ok and agent_ok:
        print(f"\nSUCCESS — profile {name} is active.")
        print("Remaining step (Rule 2/3): a live end-to-end SMS/call on this "
              "modem,\nthen set verified: true in the profile.")
        return 0

    print("\nFAILED — the modem did not register or the agent is down.")
    print("Rollback: put the previous modem back, then run:")
    if prev:
        print(f"  {sys.executable} {Path(__file__).resolve()} use {prev}")
    else:
        print("  (no previous profile was recorded)")
    print("Backups made by this run:")
    for b in res["backups"]:
        print(f"  {b}")
    return 1


def cmd_use(args) -> int:
    return _switch(args.name, args.force)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        prog="modem_profile.py",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    sub.add_parser("list", help="show all profiles").set_defaults(fn=cmd_list)

    sp = sub.add_parser("show", help="print a profile (default: active)")
    sp.add_argument("name", nargs="?", default="")
    sp.set_defaults(fn=cmd_show)

    sub.add_parser("status", help="active profile vs plugged-in device").set_defaults(fn=cmd_status)

    sp = sub.add_parser("new", help="create an unverified template profile")
    sp.add_argument("name")
    sp.add_argument("--modem-model", default="")
    sp.add_argument("--vid-pid", default="")
    sp.add_argument("--dongle-name", default="")
    sp.add_argument("--audio", default="")
    sp.add_argument("--data", default="")
    sp.add_argument("--sim-phone", default="")
    sp.add_argument("--force", action="store_true")
    sp.set_defaults(fn=cmd_new)

    sp = sub.add_parser("capture", help="create a verified profile from the "
                                        "live state")
    sp.add_argument("name")
    sp.add_argument("--force", action="store_true")
    sp.set_defaults(fn=cmd_capture)

    sp = sub.add_parser("probe", help="inspect the plugged-in modem; "
                                      "--commit writes the findings")
    sp.add_argument("--commit", default="", metavar="NAME")
    sp.add_argument("--audio", default="",
                    help="serial PCM audio tty (default: guessed)")
    sp.add_argument("--data", default="",
                    help="data tty (default: the AT port, via AT+CGMM)")
    sp.add_argument("--alsadev", default="",
                    help="UAC ALSA card, e.g. hw:CARD=EC25EUX,DEV=0 "
                         "(default: auto-detected from /proc/asound/cards "
                         "when USBCFG has uac=1)")
    sp.set_defaults(fn=cmd_probe)

    sp = sub.add_parser("init", help="(installer) create profile from "
                                     "answers + render artifacts")
    sp.add_argument("name")
    sp.add_argument("--modem-model", default="")
    sp.add_argument("--vid-pid", default="")
    sp.add_argument("--dongle-name", default="")
    sp.add_argument("--audio", default="")
    sp.add_argument("--data", default="")
    sp.add_argument("--sim-phone", default="")
    sp.add_argument("--interfaces", default="00,01,02")
    sp.add_argument("--force", action="store_true")
    sp.set_defaults(fn=cmd_init)

    sp = sub.add_parser("apply", help="re-render udev + dongle.conf for a "
                                      "profile (no restarts)")
    sp.add_argument("name")
    sp.set_defaults(fn=cmd_apply)

    sp = sub.add_parser("use", help="switch to a profile (full flow)")
    sp.add_argument("name")
    sp.add_argument("--force", action="store_true",
                    help="allow an unverified profile")
    sp.set_defaults(fn=cmd_use)

    args = ap.parse_args(argv)
    try:
        return args.fn(args)
    except ProfileError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    sys.exit(main())
