#!/usr/bin/env python3
"""Modem profile manager — per-modem config with one-command swap.

SimBridge runs on a USB GSM modem. Everything that is modem-specific
lives in four places:

  1. /etc/udev/rules.d/92-dongle.rules   — VID/PID + USB interface number
                                            -> stable dongle_ifN symlinks,
                                            owner asterisk:dialout
  2. /etc/asterisk/dongle.conf           — channel name + voice (audio=
                                            serial PCM tty, or alsadev=
                                            UAC ALSA card) + data= devices
  3. /etc/simbridge/simbridge.yaml       — asterisk.dongle, sim.modem_model
  4. /etc/asterisk/asterisk-globals.conf — MODEM_ID (generated from #3 by
                                            scripts/generate_asterisk_config.py)

A *profile* is a YAML file with all of the above in one record:

  /etc/simbridge/modem-profiles/<name>.yaml
  /etc/simbridge/active_modem             (one-line pointer to the active name)

Subcommands:

  list                          show all profiles, mark the active one
  show [name]                   print a profile (default: active)
  status                        active profile vs. plugged-in USB device,
                                dongle + agent state
  new <name>                    create an unverified template profile
  capture <name>                create a verified profile from the live
                                state (the currently working modem)
  probe [--commit <name>]       inspect the plugged-in modem (ports, AT
                                answers, USBCFG); --commit writes/updates
                                the profile from the findings
  init <name> ...               (used by deploy/install.py) create a profile
                                from installer answers and render artifacts
  apply <name>                  re-render udev rules + dongle.conf for a
                                profile, no service restarts
  use <name> [--force]          SWITCH: back up -> render artifacts ->
                                update simbridge.yaml -> regenerate globals
                                -> restart services -> verify -> report

Rules honored:
  Rule 1 — this script is the ONLY mechanism that renders dongle.conf and
           the dongle udev rules. deploy/install.py (fresh installs) calls
           `init` instead of writing the files itself; the globals are
           regenerated by the existing scripts/generate_asterisk_config.py.
  Rule 2 — a profile is `verified: true` only after a live end-to-end
           check; `use` refuses an unverified profile without --force.
  Rule 4 — `use` backs up every file it changes (timestamped .bak-*) and
           is idempotent: switching to the already-active profile whose
           artifacts are in sync changes nothing and restarts nothing.
  Rule 5 — profiles contain no secrets.

Live swap workflow (modem physically replaced):

  python3 modem_profile.py probe                 # inspect the new modem
  python3 modem_profile.py probe --commit quectel-ec25 --data /dev/ttyUSB2
                                                 # fix the profile
  python3 modem_profile.py use quectel-ec25 --force
  # on failure: put the old modem back, then
  python3 modem_profile.py use huawei-e161

Test hooks (used by tests/test_modem_profile.py): all state paths can be
redirected via environment variables, and all shell commands go through
the single run() function so tests can stub it.
"""

