def parse_dongle_conf(text: str) -> dict:
    """Parse [section] name + audio/data/alsadev from a dongle.conf text."""
    section = ""
    dev = {"audio": "", "data": "", "alsadev": ""}
    for line in text.splitlines():
        line = line.strip()
        m = re.match(r"^\[(.+)\]$", line)
        if m:
            section = m.group(1)
            continue
        if section and section != "general":
            m = re.match(r"^(audio|data|alsadev)\s*=\s*(\S+)", line)
            if m:
                dev[m.group(1)] = m.group(2)
    return {"section": section, **dev}


def parse_udev_all(text: str) -> dict:
    """Parse `udevadm info -q all` output into a dict (last value wins).

    Property lines carry a one-letter record prefix (properties are
    'E: KEY=value'; also 'P:'/'M:'/'R:'/'U:' lines without '=') — the
    prefix is optional so plain KEY=value dumps parse too.
    """
    out = {}
    for line in text.splitlines():
        m = re.match(r"^(?:[A-Z]: )?([A-Za-z0-9_]+)=(.*)$", line)
        if m:
            out[m.group(1)] = m.group(2).strip('"')
    return out


def _udev_meta(dev: str) -> dict:
    """udevadm metadata for device *dev*.

    Symlinks are resolved first: `udevadm info -n` given a symlink NAME
    (e.g. /dev/dongle_if1) returns a reduced property set (no
    ID_USB_INTERFACE_NUM / ID_MODEL_ID) on this system, while the
    resolved device path (/dev/ttyUSB1) returns the full set.
    """
    dev_real = os.path.realpath(dev)
    r = run(f"udevadm info -q all -n {shlex.quote(dev_real)} 2>/dev/null")
    return parse_udev_all(r.stdout)


def _capture_from_live() -> dict:
    """Build a profile dict from the live state (modem must be plugged in)."""
    ps = paths()
    if not ps["dongle_conf"].is_file():
        raise ProfileError(f"no {ps['dongle_conf']} — nothing to capture")
    dc = parse_dongle_conf(ps["dongle_conf"].read_text(errors="replace"))
    if not dc["section"] or not dc["data"] or \
            (not dc["alsadev"] and not dc["audio"]):
        raise ProfileError(
            f"dongle.conf: cannot find [section] with data= and a voice "
            f"port (audio= or alsadev= for UAC) "
            f"(got section={dc['section']!r})")

    yaml_text = ""
    if ps["config_yaml"].is_file():
        yaml_text = ps["config_yaml"].read_text(errors="replace")
    dongle_name = _yaml_field(yaml_text, "asterisk", "dongle") or dc["section"]
    modem_model = _yaml_field(yaml_text, "sim", "modem_model")
    sim_phone = _yaml_field(yaml_text, "sim", "phone")

    # vid:pid + interface map from udev (authoritative) with an lsusb-line
    # fallback for the vid:pid only.
    vid = pid = ""
    udev_map = []
    r = run("ls -1 /dev/dongle_if* 2>/dev/null")
    for dev in r.stdout.split():
        meta = _udev_meta(dev)
        iface = meta.get("ID_USB_INTERFACE_NUM", "")
        if meta.get("ID_VENDOR_ID"):
            vid = meta["ID_VENDOR_ID"]
        if meta.get("ID_MODEL_ID"):
            pid = meta["ID_MODEL_ID"]
        if re.fullmatch(r"\d{2}", iface):
            udev_map.append({"iface": iface, "symlink": Path(dev).name})
    if not (vid and pid) and modem_model:
        m = re.search(r"\bID\s+([0-9a-fA-F]{4}):([0-9a-fA-F]{4})", modem_model)
        if m:
            vid, pid = m.group(1), m.group(2)
    udev_map.sort(key=lambda e: e["iface"])

    prof = {
        "name": dongle_name,
        "modem_model": modem_model,
        "vid_pid": f"{vid}:{pid}" if vid and pid else "",
        "dongle_name": dongle_name,
        "audio_device": "" if dc["alsadev"] else dc["audio"],
        "data_device": dc["data"],
        "sim_phone": sim_phone,
        "udev": udev_map,
        "verified": True,   # captured from a currently working live state
        "notes": "captured from live state by modem_profile.py capture",
    }
    if dc["alsadev"]:
        prof["alsadev"] = dc["alsadev"]
    return prof


# termios speed slots hold speed INDICES (termios.B115200 == 15 on Linux),
# not baud-rate numbers — mapping from the rate to the constant name.
_AT_SPEEDS = {9600: "B9600", 19200: "B19200", 38400: "B38400",
              57600: "B57600", 115200: "B115200"}


def at_query(dev: str, at_cmd: str, baud: int = 115200,
             timeout: float = 2.5) -> str:
    """Send one AT command to *dev* (raw termios, stdlib only).

    Returns the response body with echo and the final OK/ERROR line
    stripped; "" on any failure (unopenable port, no answer).
    """
    import fcntl
    import termios
    import tty

    try:
        fd = os.open(dev, os.O_RDWR | os.O_NOCTTY)
    except OSError:
        return ""
    orig = None
    try:
        orig = termios.tcgetattr(fd)   # kept for restore in finally
        tty.setraw(fd)
        attrs = termios.tcgetattr(fd)  # raw-mode attrs, current speed
        # tcgetattr list layout: [iflag, oflag, cflag, lflag, ispeed,
        # ospeed, cc] — the speed slots hold speed INDICES (termios.B115200
        # == 15 on Linux), not baud-rate numbers. This RHEL Python build's
        # termios exposes no cfsetspeed/cfsetispeed, so set the slots
        # directly.
        speed = getattr(termios, _AT_SPEEDS.get(baud, "B115200"))
        attrs[4] = speed
        attrs[5] = speed
        termios.tcsetattr(fd, termios.TCSANOW, attrs)
        # select() is the ONLY arbiter: a blocking os.read() on a serial
        # tty can sleep forever after select() reports the fd ready with
        # nothing pending (observed live on the EC25 diag port, kernel
        # stuck in n_tty_read). O_NONBLOCK turns that into EAGAIN.
        flags = fcntl.fcntl(fd, fcntl.F_GETFL)
        fcntl.fcntl(fd, fcntl.F_SETFL, flags | os.O_NONBLOCK)
        try:
            termios.tcflush(fd, termios.TCIFLUSH)
        except termios.error:
            pass
        os.write(fd, (at_cmd + "\r").encode())
        chunks = []
        deadline = time.time() + timeout
        while time.time() < deadline:
            rlist, _, _ = select.select([fd], [], [], 0.25)
            if not rlist:
                continue
            try:
                chunk = os.read(fd, 1024)
            except BlockingIOError:
                continue           # select race: no data yet, keep polling
            except OSError:
                break
            if not chunk:
                break
            chunks.append(chunk)
            if b"OK" in chunk or b"ERROR" in chunk:
                break  # terminal response line received
        resp = b"".join(chunks).decode("utf-8", "replace")
        lines = [ln.strip() for ln in resp.splitlines() if ln.strip()]
        body = [ln for ln in lines if ln not in ("OK", "ERROR")
                and ln != at_cmd.replace("\r", "")]
        return "\n".join(body)
    finally:
        if orig is not None:
            try:
                termios.tcsetattr(fd, termios.TCSANOW, orig)
            except (termios.error, OSError):
                pass
        os.close(fd)


def _probe_devices() -> list:
    """Enumerate ttyUSB/ttyACM ports with their udev metadata."""
    r = run("ls -1 /dev/ttyUSB* /dev/ttyACM* 2>/dev/null")
    devs = []
    for dev in r.stdout.split():
        meta = _udev_meta(dev)
        devs.append({
            "dev": dev,
            "vid": meta.get("ID_VENDOR_ID", ""),
            "pid": meta.get("ID_MODEL_ID", ""),
            "iface": meta.get("ID_USB_INTERFACE_NUM", ""),
            "model": meta.get("ID_MODEL", ""),
        })
    return devs


