def render_dongle_conf(p: dict) -> str:
    """Render /etc/asterisk/dongle.conf for profile *p*.

    Modem-specific: the channel name and the voice/data devices. Voice
    is either audio=<serial PCM tty> or alsadev=<ALSA card> (UAC,
    chan_dongle patch 0003) — the profile carries one or the other.
    App-level constants mirror asterisk/dongle.conf.example.
    """
    vid = p.get("vid_pid") or "unknown vid:pid"
    n = p["dongle_name"]
    alsadev = p.get("alsadev") or ""
    voice_line = (f"alsadev = {alsadev}\n" if alsadev
                  else f"audio = {p['audio_device']}\n")
    return (
        "; SimBridge chan_dongle config — GENERATED by scripts/modem_profile.py\n"
        f"; Profile: {p['name']} — {p.get('modem_model', '')} ({vid})\n"
        "; Do NOT edit manually. To swap modems:\n"
        ";   python3 /opt/simbridge/scripts/modem_profile.py use <profile>\n"
        "; App constants mirror asterisk/dongle.conf.example.\n"
        "\n"
        "[general]\n"
        f"interval={DONGLE_INTERVAL}\n"
        "\n"
        f"[{n}]\n"
        f"{voice_line}"
        f"data = {p['data_device']}\n"
        f"context = {DONGLE_CONTEXT}\n"
        f"group = {DONGLE_GROUP}\n"
        "smsaspdu = yes\n"
        "autodeletesms = yes\n"
    )


UDEV_RULE_TEMPLATE = (
    'SUBSYSTEM=="tty", ENV{{ID_MODEL_ID}}=="{pid}", '
    'ENV{{ID_USB_INTERFACE_NUM}}=="{iface}", SYMLINK+="{symlink}", '
    'OWNER="asterisk", GROUP="dialout", MODE="0660"'
)

# Tag telling ModemManager to leave this modem alone. chan_dongle owns the
# AT/audio ports; when MM probes the dongle it holds the AT port open and
# chan_dongle then fails to open it (EBUSY) — observed live with the EC25,
# whose vendor rules (77-mm-quectel-port-types.rules) mark the AT port with
# high confidence, so even the strict filter policy (the MM default) probes
# it. ID_MM_DEVICE_IGNORE is honored under all filter policies, strict
# included (mm-filter.c: mm_filter_port() checks it before the plugin
# allowlists, under MM_FILTER_RULE_EXPLICIT_BLOCKLIST).
#
# The tag must be present on the PORTS themselves, not only on the USB
# composite device. On RHEL9 (MM 1.20.2) the filter's physdev lookup
# (kernel_device_get_global_property → first devtype "usb_device" ancestor)
# did not surface the composite's udev properties even though the tag was
# in the udev DB at the fresh plug-in event — the modem was created
# anyway, and MM kept the AT port open. What IS reliably visible to the
# filter is the port's own property list (the vendor rules'
# ID_MM_PORT_TYPE_* tags on the tty devices are what MM acted on).
# udev ATTR{} matches a device's own attributes, ATTRS{} its ancestors'
# (udev(7)) — so two rules are needed to cover both the composite and
# every device in its subtree (tty, usbmisc/QMI, net ports alike):
UDEV_MM_IGNORE_SELF_TEMPLATE = (
    'SUBSYSTEM=="usb", ATTR{{idVendor}}=="{vid}", '
    'ATTR{{idProduct}}=="{pid}", ENV{{ID_MM_DEVICE_IGNORE}}="1"'
)
UDEV_MM_IGNORE_SUBTREE_TEMPLATE = (
    'ATTRS{{idVendor}}=="{vid}", '
    'ATTRS{{idProduct}}=="{pid}", ENV{{ID_MM_DEVICE_IGNORE}}="1"'
)


def render_udev_rules(p: dict) -> str:
    """Render /etc/udev/rules.d/92-dongle.rules for profile *p*.

    The per-port symlink rules are keyed by ID_MODEL_ID (the USB PID —
    stable across ports and firmware updates of the same model) plus
    ID_USB_INTERFACE_NUM (the interface number — stable; the ttyUSB
    index is NOT). Two ID_MM_DEVICE_IGNORE rules keep ModemManager off
    the dongle: one on the USB composite device (ATTR = own attributes),
    one on every device in its subtree (ATTRS = ancestor attributes) —
    see UDEV_MM_IGNORE_*_TEMPLATE for why both are needed.
    """
    parts = (p.get("vid_pid") or "").split(":")
    vid = parts[0] if len(parts) == 2 else ""
    pid = parts[1] if len(parts) == 2 else ""
    if not pid:
        raise ProfileError(f"profile {p['name']}: no vid_pid — "
                           "cannot render udev rules")
    if not p.get("udev"):
        raise ProfileError(f"profile {p['name']}: empty udev mapping")
    lines = [
        "# SimBridge dongle symlinks — GENERATED by scripts/modem_profile.py",
        f"# Profile: {p['name']} — {p.get('modem_model', '')} "
        f"({p.get('vid_pid', '')})",
        "# Do NOT edit manually.",
    ]
    if vid:
        lines.append(UDEV_MM_IGNORE_SELF_TEMPLATE.format(vid=vid, pid=pid))
        lines.append(UDEV_MM_IGNORE_SUBTREE_TEMPLATE.format(vid=vid, pid=pid))
    for e in p["udev"]:
        lines.append(UDEV_RULE_TEMPLATE.format(pid=pid, iface=e["iface"],
                                               symlink=e["symlink"]))
    return "\n".join(lines) + "\n"


def _retire_legacy_udev_rule(p: dict) -> None:
    """Remove the S01-era duplicate 99-dongle.rules when (and only when)
    it keys the same USB PID as the active profile."""
    legacy = paths()["udev_legacy_rule"]
    if not legacy.is_file():
        return
    pid = (p.get("vid_pid") or "").split(":")[1]
    # udev ENV{} syntax: the closing brace sits between the key and ==
    m = re.search(r'ID_MODEL_ID\}=="([0-9a-fA-F]{4})"',
                  legacy.read_text(errors="replace"))
    if m and pid and m.group(1).lower() == pid.lower():
        b = backup(legacy)
        legacy.unlink()
        print(f"  Retired legacy duplicate rule: {legacy}"
              + (f" (backup {b})" if b else ""))
    elif m:
        print(f"  [warn] {legacy.name} keys a different modem "
              f"(PID {m.group(1)}) — left untouched, review manually")


def apply_artifacts(p: dict, backup_old: bool = True) -> dict:
    """Render udev rules + dongle.conf from profile *p*.

    Shared by `use` (full switch) and `init`/`apply` (fresh install /
    manual re-render). Never restarts services — the caller decides.
    Returns {"backups": [...], "udev": path-or-None, "dongle_conf": path}.
    """
    ps = paths()
    backups = []
    if backup_old:
        for f in (ps["udev_rule"], ps["dongle_conf"], ps["config_yaml"],
                  ps["active"]):
            b = backup(f)
            if b:
                backups.append(b)

    udev_written = None
    if p.get("vid_pid") and p.get("udev"):
        udev_text = render_udev_rules(p)
        if not ps["udev_rule"].is_file() \
                or ps["udev_rule"].read_text() != udev_text:
            _write_atomic(ps["udev_rule"], udev_text, 0o644)
            udev_written = str(ps["udev_rule"])
            # Scoped trigger: only the two subsystems these rules act on —
            # tty (symlink rules) and usb (the ID_MM_DEVICE_IGNORE rule on
            # the physical device; ModemManager needs that change event to
            # drop a device it has already adopted). A bare `udevadm
            # trigger` re-fires every device on the box, too wide for a
            # live node.
            r = run("udevadm control --reload-rules && "
                    "udevadm trigger --subsystem-match=tty "
                    "--subsystem-match=usb")
            if r.returncode != 0:
                print("  [warn] udevadm reload/trigger: "
                      f"{(r.stdout or r.stderr).strip()[:200]}")
        _retire_legacy_udev_rule(p)
    else:
        print("  [warn] profile has no vid_pid/udev mapping — udev rules "
              "NOT rendered; set up symlinks/permissions manually")

    dtext = render_dongle_conf(p)
    if not ps["dongle_conf"].is_file() \
            or ps["dongle_conf"].read_text() != dtext:
        _write_atomic(ps["dongle_conf"], dtext, 0o644)
    return {"backups": backups, "udev": udev_written,
            "dongle_conf": str(ps["dongle_conf"])}


# ---------------------------------------------------------------------------
# simbridge.yaml — line-based surgical patch (all other bytes identical)
# ---------------------------------------------------------------------------

def _yaml_field(text: str, section: str, key: str) -> str:
    """Value of `key` inside top-level `section:`, unquoted, '' if absent."""
    in_section = False
    for line in text.splitlines():
        if not line.startswith(" ") and not line.startswith("\t"):
            in_section = line.rstrip() == section + ":"
            continue
        if in_section:
            m = re.match(rf"^\s+{re.escape(key)}:\s*(.*)$", line)
            if m:
                v = m.group(1).strip()
                if len(v) >= 2 and v[0] == '"' and v[-1] == '"':
                    v = v[1:-1]
                return v
    return ""


def patch_yaml_field(text: str, section: str, key: str, value: str,
                     quote: bool = True) -> str:
    """Replace the single `key:` line inside top-level `section:`.

    Line-based (no YAML round-trip) so every other byte of the file is
    preserved. Raises ProfileError if the section or key is missing.
    """
    val = f'"{value}"' if quote else value
    out = []
    in_section = False
    replaced = False
    for line in text.splitlines(keepends=True):
        if not line.startswith(" ") and not line.startswith("\t"):
            in_section = line.rstrip("\n").rstrip() == section + ":"
        if in_section and not replaced \
                and re.match(rf"^\s+{re.escape(key)}\s*:", line):
            indent = re.match(r"^[ \t]*", line).group(0)
            newline = "\n" if line.endswith("\n") else ""
            out.append(f"{indent}{key}: {val}{newline}")
            replaced = True
            continue
        out.append(line)
    if not replaced:
        raise ProfileError(f"simbridge.yaml: key {section}.{key} not found")
    return "".join(out)


