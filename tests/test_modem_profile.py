"""Tests for scripts/modem_profile.py (modem profiles, one-command swap).

The module is imported the same way deploy/install.py is in
test_install_noninteractive.py — module level only defines constants,
renderers and functions; main() is guarded by ``__main__``.

All state paths are redirected into tmp_path via environment variables
and every shell command goes through the module's single run() hook,
which the ``st`` fixture stubs. No test touches real udev, Asterisk,
systemd, or serial ports.

Covered:
- validate_profile / render_profile round-trip + invalid-profile rejects
- render_dongle_conf (audio/data + app-level constants)
- render_udev_rules (PID + interface-number keying; refuse when missing;
  ID_MM_DEVICE_IGNORE on the USB device AND every port of its subtree —
  ModemManager isolation, see the EBUSY notes in the script)
- patch_yaml_field (surgical — every other line byte-identical)
- backup()
- apply_artifacts (render + backups, idempotency, legacy 99-dongle.rules
  retirement only for the same USB PID)
- _switch / use (verified gate, surgical yaml update, restart policy,
  idempotent no-op, rollback + exit 1 on failed verification)
- probe (AT port detection via stubbed AT answers, USBCFG, --commit
  writes an unverified profile with dongle_if<iface-as-int> symlinks)
- capture (_capture_from_live from stubbed udev state)
- list (active marker, empty dir)
- status (MATCH/MISMATCH marking, ModemManager adoption warning)
"""

