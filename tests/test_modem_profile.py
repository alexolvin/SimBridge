class TestUdevMeta:
    def test_symlink_resolved_before_query(self, st):
        # live quirk: udevadm given a symlink name returns a reduced
        # property set; the query must go to the resolved device node
        real = st.root / "ttyX"
        real.write_text("")
        link = st.root / "dongle_if1"
        link.symlink_to(real)
        (st.root / "stub_meta_ttyX").write_text(
            "ID_VENDOR_ID=12d1\nID_MODEL_ID=1001\n"
            "ID_USB_INTERFACE_NUM=01\n")
        meta = modem_profile._udev_meta(str(link))
        assert meta["ID_MODEL_ID"] == "1001"
        assert meta["ID_USB_INTERFACE_NUM"] == "01"
        # the udevadm call carried the resolved path, not the symlink
        udev_calls = [c for c in st.calls if "udevadm" in c]
        assert udev_calls
        assert all(str(real) in c for c in udev_calls)
        assert not any(str(link) in c for c in udev_calls)

    def test_non_symlink_passed_through(self, st):
        (st.root / "stub_meta_ttyUSB9").write_text("ID_MODEL_ID=abcd\n")
        meta = modem_profile._udev_meta("/dev/ttyUSB9")
        assert meta["ID_MODEL_ID"] == "abcd"


