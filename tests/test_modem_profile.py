class TestPatchYaml:
    def test_surgical_update_other_lines_identical(self, st):
        new = modem_profile.patch_yaml_field(LIVE_YAML, "asterisk", "dongle",
                                             "gsm", quote=False)
        new = modem_profile.patch_yaml_field(new, "sim", "modem_model",
                                             "new model: with colon")
        # every line that was not the target is byte-identical
        skip_old = {"  dongle: gsm", '  modem_model: "Bus 003 Device 002: '
                                     'ID 12d1:1001 Huawei"'}
        skip_new = {"  dongle: gsm", '  modem_model: "new model: with colon"'}
        old_lines = [l for l in LIVE_YAML.splitlines() if l not in skip_old]
        new_lines = [l for l in new.splitlines() if l not in skip_new]
        assert old_lines == new_lines
        assert "  dongle: gsm\n" in new
        assert '  modem_model: "new model: with colon"\n' in new
        # untouched values survive
        assert "  ring_wait_seconds: 18" in new
        assert '  phone: "+79000000000"' in new

    def test_missing_section_raises(self, st):
        with pytest.raises(modem_profile.ProfileError):
            modem_profile.patch_yaml_field(LIVE_YAML, "nonexistent", "k", "v")

    def test_missing_key_raises(self, st):
        with pytest.raises(modem_profile.ProfileError):
            modem_profile.patch_yaml_field(LIVE_YAML, "asterisk",
                                           "not_a_key", "v")

    def test_yaml_field_reader(self, st):
        assert modem_profile._yaml_field(LIVE_YAML, "asterisk", "dongle") \
            == "gsm"
        assert modem_profile._yaml_field(LIVE_YAML, "sim", "phone") \
            == "+79000000000"
        assert modem_profile._yaml_field(LIVE_YAML, "sim", "absent") == ""


