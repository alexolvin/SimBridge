class TestProfileSchema:
    def test_render_load_roundtrip(self, st):
        p = _hprofile()
        modem_profile.write_profile(p)
        loaded = modem_profile.load_profile(
            st.root / "profiles" / "huawei-e161.yaml")
        assert loaded == p

    def test_write_rejects_invalid_name(self, st):
        with pytest.raises(modem_profile.ProfileError):
            modem_profile.profile_path("Huawei E161")

    @pytest.mark.parametrize("mutate,match", [
        (lambda p: p.pop("dongle_name"), "dongle_name"),
        (lambda p: p.update(vid_pid="12d1"), "vid_pid"),
        (lambda p: p.update(name="Bad Name"), "name"),
        (lambda p: p.update(verified="yes"), "verified"),
        (lambda p: p.update(udev=[{"iface": "1", "symlink": "x"}]),
         "iface"),
        (lambda p: p.update(udev="nope"), "udev"),
    ])
    def test_validate_rejects(self, st, mutate, match):
        p = _hprofile()
        mutate(p)
        errs = modem_profile.validate_profile(p)
        assert any(match in e for e in errs), errs

    def test_valid_profile_no_errors(self, st):
        assert modem_profile.validate_profile(_hprofile()) == []


