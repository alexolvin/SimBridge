class TestApplyArtifacts:
    def test_renders_and_backs_up(self, st):
        (st.root / "dongle.conf").write_text("old")
        (st.root / "92-dongle.rules").write_text("old")
        _write_live_yaml(st)
        (st.root / "active_modem").write_text("oldname")
        res = modem_profile.apply_artifacts(_hprofile())
        udev = (st.root / "92-dongle.rules").read_text()
        assert 'ENV{ID_MODEL_ID}=="1001"' in udev
        assert "audio = /dev/dongle_if1" in \
            (st.root / "dongle.conf").read_text()
        # 4 artifacts backed up (udev, dongle.conf, yaml, active pointer)
        assert len(res["backups"]) == 4
        assert any("92-dongle.rules.bak-" in b for b in res["backups"])
        assert any("dongle.conf.bak-" in b for b in res["backups"])
        assert any("simbridge.yaml.bak-" in b for b in res["backups"])
        assert any("active_modem.bak-" in b for b in res["backups"])
        # udev was reloaded (tty + usb-scoped trigger: the usb change
        # event carries the ID_MM_DEVICE_IGNORE tag to ModemManager)
        assert any("udevadm trigger --subsystem-match=tty "
                   "--subsystem-match=usb" in c for c in st.calls)

    def test_idempotent_second_call_no_write_no_reload(self, st):
        p = _hprofile()
        modem_profile.apply_artifacts(p)
        u1 = (st.root / "92-dongle.rules").read_bytes()
        d1 = (st.root / "dongle.conf").read_bytes()
        reloads = len([c for c in st.calls if "udevadm control" in c])
        res = modem_profile.apply_artifacts(p)
        assert res["udev"] is None
        assert len([c for c in st.calls if "udevadm control" in c]) == reloads
        assert (st.root / "92-dongle.rules").read_bytes() == u1
        assert (st.root / "dongle.conf").read_bytes() == d1

    def test_legacy_udev_same_pid_retired_with_backup(self, st):
        legacy = st.root / "99-dongle.rules"
        legacy.write_text(
            'SUBSYSTEM=="tty", ENV{ID_MODEL_ID}=="1001", '
            'ENV{ID_USB_INTERFACE_NUM}=="00", SYMLINK+="dongle_if0", '
            'OWNER="asterisk", GROUP="dialout", MODE="0660"\n')
        modem_profile.apply_artifacts(_hprofile())
        assert not legacy.exists()
        assert len(list(st.root.glob("99-dongle.rules.bak-*"))) == 1

    def test_legacy_udev_other_pid_kept(self, st, capsys):
        legacy = st.root / "99-dongle.rules"
        legacy.write_text(
            'SUBSYSTEM=="tty", ENV{ID_MODEL_ID}=="beef", '
            'ENV{ID_USB_INTERFACE_NUM}=="00", SYMLINK+="other0", '
            'OWNER="root", GROUP="root", MODE="0660"\n')
        modem_profile.apply_artifacts(_hprofile())
        assert legacy.exists()  # foreign rule — left for manual review
        out = capsys.readouterr().out
        assert "different modem" in out

    def test_no_vid_pid_skips_udev_with_warning(self, st, capsys):
        res = modem_profile.apply_artifacts(_hprofile(vid_pid="", udev=[]))
        assert res["udev"] is None
        assert not (st.root / "92-dongle.rules").exists()
        assert "NOT rendered" in capsys.readouterr().out


