class TestSwitch:
    def test_unverified_refused_without_force(self, st):
        modem_profile.write_profile(_hprofile(verified=False))
        _write_live_yaml(st)
        with pytest.raises(modem_profile.ProfileError, match="NOT verified"):
            modem_profile._switch("huawei-e161", force=False)
        assert not (st.root / "active_modem").exists()
        assert not any("systemctl restart" in c for c in st.calls)

    def test_full_switch_success(self, st, capsys):
        modem_profile.write_profile(_hprofile())
        _write_live_yaml(st)
        (st.root / "active_modem").write_text("old-profile")
        (st.root / "stub_dongle_show").write_text(
            "gsm: 12d1:1001 /dev/dongle_if1 /dev/dongle_if2\n")
        rc = modem_profile._switch("huawei-e161", force=False)
        assert rc == 0
        # surgical yaml update: only the two fields changed
        y = st.yaml()
        assert "  dongle: gsm\n" in y
        assert '  modem_model: "Huawei E161/E169/E620/E800 HSDPA Modem"' \
            in y
        assert "  ring_wait_seconds: 18" in y
        assert (st.root / "active_modem").read_text().strip() == "huawei-e161"
        # restarts: asterisk yes; agent NO (channel name unchanged)
        assert any(c == "systemctl restart asterisk" for c in st.calls)
        assert not any("simbridge-agent" in c and "restart" in c
                       for c in st.calls)
        # globals regenerated by the existing generator
        assert any("generate_asterisk_config.py" in c for c in st.calls)
        assert "SUCCESS" in capsys.readouterr().out

    def test_channel_rename_restarts_agent(self, st):
        modem_profile.write_profile(_hprofile(dongle_name="modem2"))
        _write_live_yaml(st)
        (st.root / "stub_dongle_show").write_text("modem2: ONLINE\n")
        rc = modem_profile._switch("huawei-e161", force=False)
        assert rc == 0
        assert "  dongle: modem2\n" in st.yaml()
        assert any("systemctl restart simbridge-agent" in c
                   for c in st.calls)

    def test_already_active_and_in_sync_is_noop(self, st, capsys):
        p = _hprofile()
        modem_profile.write_profile(p)
        # bring the live state into sync with the profile
        _write_live_yaml(st, LIVE_YAML.replace(
            '  modem_model: "Bus 003 Device 002: ID 12d1:1001 Huawei"',
            '  modem_model: "Huawei E161/E169/E620/E800 HSDPA Modem"'))
        modem_profile.apply_artifacts(p)
        modem_profile.write_active("huawei-e161")
        d_before = (st.root / "dongle.conf").read_bytes()
        rc = modem_profile._switch("huawei-e161", force=False)
        assert rc == 0
        assert not any("systemctl restart" in c for c in st.calls)
        assert (st.root / "dongle.conf").read_bytes() == d_before
        out = capsys.readouterr().out
        assert "already active" in out and "no restarts" in out

    def test_failed_verification_returns_1_and_rollback(self, st, capsys):
        modem_profile.write_profile(_hprofile())
        _write_live_yaml(st)
        (st.root / "active_modem").write_text("old-profile")
        # channel name "gsm" must NOT appear — otherwise verification passes
        (st.root / "stub_dongle_show").write_text("dongle0: OFFLINE\n")
        rc = modem_profile._switch("huawei-e161", force=False)
        assert rc == 1
        out = capsys.readouterr().out
        assert "FAILED" in out
        assert "use old-profile" in out

    def test_missing_profile(self, st):
        _write_live_yaml(st)
        with pytest.raises(modem_profile.ProfileError, match="no such profile"):
            modem_profile._switch("ghost", force=False)


